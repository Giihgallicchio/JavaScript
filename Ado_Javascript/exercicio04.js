/*
Programa que verifica se o número inteiro
é par ou ímpar utilizando o resto da divisão
*/

let numero = 5;

// O resto da divisão por 2 igual a zero indica que o número é par
if (numero % 2 == 0) {
    console.log(numero + " é par");
} else {
    console.log(numero + " é ímpar");
}